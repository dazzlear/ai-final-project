"""Module 5 — Evaluation summary.

Reads the scores pkl files produced by Modules 3 and 4, then prints AUC
and TPR@5%FPR for every method and every target model.

Produces:
    outputs/evaluation_summary.csv   — one row per (method, model)
"""
import csv
import pickle
from pathlib import Path

from src.metrics import compute_auc, tpr_at_fpr

# Configuration and paths
DRIVE     = "/content/drive/MyDrive/ai-final-project"
SCORE_DIR = Path(f"{DRIVE}/outputs/scores")
EVAL_OUT  = Path(f"{DRIVE}/outputs/evaluation_summary.csv")

# Target models and MIA detection methods to evaluate
MODELS  = ["pythia-2.8b", "gpt-neo-1.3B", "opt-1.3b"]
METHODS = ["Neighbor", "PPL", "Zlib", "Lowercase", "Smaller Ref", "Min-K%"]

# Load scores from pickle files generated by Modules 3 and 4
data = {}
for model in MODELS:
    path = SCORE_DIR / f"scores_{model}.pkl"
    if path.exists():
        data[model] = pickle.load(open(path, "rb"))
    else:
        print(f"WARNING: {path} not found — skipping {model}")

if not data:
    raise FileNotFoundError(
        "No scores pkl files found. Run Modules 3 and 4 first."
    )

# Print evaluation results table with AUC and TPR@5%FPR metrics
header = f"{'Method':<14}" + "".join(f"  {m:>16}" for m in data) + "  {'Avg':>8}"
print("\n" + "=" * len(header))
print(header)
print("=" * len(header))

for method in METHODS:
    row_str  = f"{method:<14}"
    auc_vals = []
    for model in MODELS:
        if model not in data:
            row_str += f"  {'N/A':>16}"
            continue
        sc  = data[model]["scores"].get(method, [])
        lbl = data[model]["labels"]
        if not sc:
            row_str += f"  {'N/A':>16}"
            continue
        auc = compute_auc(sc, lbl)
        tpr = tpr_at_fpr(sc, lbl)
        row_str += f"  AUC={auc:.3f} TPR={tpr:.3f}"
        auc_vals.append(auc)
    avg = sum(auc_vals) / len(auc_vals) if auc_vals else float("nan")
    row_str += f"  {avg:>8.3f}"
    print(row_str)

print("=" * len(header) + "\n")

# Save evaluation summary to CSV file
with open(EVAL_OUT, "w", newline="") as f:
    writer = csv.writer(f)
    writer.writerow(["method", "model", "auc", "tpr_at_5fpr"])
    for model in MODELS:
        if model not in data:
            continue
        for method in METHODS:
            sc  = data[model]["scores"].get(method, [])
            lbl = data[model]["labels"]
            if not sc:
                continue
            auc = compute_auc(sc, lbl)
            tpr = tpr_at_fpr(sc, lbl)
            writer.writerow([method, model, f"{auc:.4f}", f"{tpr:.4f}"])

print(f"Saved → {EVAL_OUT}")